def patch_document(path: Path) -> None:
    doc = Document(str(path))
    paras = doc.paragraphs
    missing = [i for i in CLAIM_REPLACEMENTS if i >= len(paras)]
    if missing:
        raise SystemExit(f"paragraph index out of range: {missing} (n={len(paras)})")
    for idx, text in CLAIM_REPLACEMENTS.items():
        set_para_text(paras[idx], text)
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(path))


